  List<Map<String, dynamic>> _getFilteredReports() {
    final query = _searchController.text.trim().toLowerCase();
    return _reports.where((r) {
      final matchesQuery = query.isEmpty ||
          (r['title'] as String).toLowerCase().contains(query) ||
          (r['description'] as String).toLowerCase().contains(query) ||
          (r['scope'] as String).toLowerCase().contains(query);

      final matchesType = _selectedType == 'All' ||
          (r['type'] as String).toLowerCase() == _selectedType.toLowerCase() ||
          (r['domain'] as String).toLowerCase() == _selectedType.toLowerCase();

      final matchesScope = _selectedScope == 'All Scopes' ||
          (r['scope'] as String).toLowerCase() ==
              _selectedScope.toLowerCase().replaceAll(' (all)', '');

      final matchesPeriod = _selectedPeriod == 'All Periods' ||
          (r['period'] as String).toLowerCase() ==
              _selectedPeriod.toLowerCase();

      return matchesQuery && matchesType && matchesScope && matchesPeriod;
    }).toList();
  }

